export function legacyVote(round, d) {
  if (round.demo) return [d[5], d[4]];
  const w = weights[legacy.indexOf(d)],
    keys = d[3].split('|'),
    skip = /피해야|피할|줄여야|비추천|하지 말아야|포기해야/.test(round.q);
  const assessments = round.opts.map((o) => {
    let best = 0,
      reason = '';
    lenses.forEach(([pattern, note], j) => {
      const hits = pattern.split('|').filter((k) => o.includes(k));
      if (!hits.length) return;
      const context = pattern.split('|').some((k) => round.q.includes(k));
      const score =
        Number(w[j]) + Math.min(hits.length, 2) * 0.25 + (context ? 0.4 : 0);
      if (score > best) {
        best = score;
        reason = note;
      }
    });
    return {
      score: best + keys.filter((k) => o.includes(k)).length * 0.8,
      reason:
        reason ||
        '우선순위에 직접 연결되는 방법이에요. 일주일 동안 시도한 뒤 결과를 점검하겠어요.',
    };
  });
  const scores = assessments.map((a) => a.score),
    target = skip ? Math.min(...scores) : Math.max(...scores);
  const picked = scores
    .map((s, i) => (s === target ? i : -1))
    .filter((i) => i >= 0);
  if (!target || picked.length !== 1)
    return [
      -1,
      '저는 ‘' +
        d[2] +
        '’을 우선해요. 이 기준으로 비교하려면 각 선택지의 구체적인 학습 방법이나 목표가 더 필요해요.',
    ];
  const i = picked[0];
  return [
    i,
    skip
      ? '제 기준인 ‘' +
        d[2] +
        '’에 비춰 보면 다른 선택지를 먼저 챙기고 싶어요. 시간이 부족할 때는 이 활동부터 줄이겠어요.'
      : '제 기준은 ‘' + d[2] + '’이에요. ' + assessments[i].reason,
  ];
}
